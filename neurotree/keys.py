"""Keys for attention: one short text per node (its name split into words, path words, the first line a file says
about itself, its functions, its memory titles), indexed two ways in graph.db:
  keys  SQLite FTS5 table, BM25 over words (the lexical head)
  vecs  one static code embedding per node, potion-code-16M (the semantic head; skipped if model2vec is missing)
Built once per index run, read by every query (encode once, attend many times)."""
from __future__ import annotations

import json
import os
import re
from collections import defaultdict

from .cache import file_stamp
from .privacy import is_excluded

MODEL = "minishlab/potion-code-16M-v2"
HEAD_BYTES = 4096
CODE_COMMENT_EXT = {".js", ".jsx", ".ts", ".tsx", ".mjs", ".cjs", ".rs", ".go", ".swift", ".java", ".kt", ".c", ".h",
                    ".cpp", ".hpp", ".cs", ".css", ".scss", ".sh", ".rb", ".php", ".vue", ".svelte", ".sql"}
CAMEL = re.compile(r"(?<=[a-z0-9])(?=[A-Z])|(?<=[A-Z])(?=[A-Z][a-z])")
WORD = re.compile(r"[^\W_]+")
PY_DOC = re.compile(r"""\A\s*(?:#[^\n]*\n\s*)*(?:[rRuUbB]{0,2})(\"\"\"|''')(.*?)(?:\1|\Z)""", re.S)
NOISE_LINE = re.compile(r"^(?:!?\[|<|---|```|[{}\[\]]|@ts-|eslint|prettier|use strict|copyright|\(c\)|spdx|"
                        r"!|-\*-|import |from |package |\$|\||=+$|-+$|(?:the )?(?:mit|apache|bsd|isc|gnu)\b.*licen[cs]e|"
                        r"licen[cs]e\b|licen[cs]ed (?:under|to)|see licen[cs]e|all rights reserved|auto-?generated|generated by|do not edit|this file (?:is|was) generated)", re.I)
SCHEMA = """
CREATE VIRTUAL TABLE IF NOT EXISTS keys USING fts5(name, path, body, tokenize='porter unicode61 remove_diacritics 2');
CREATE TABLE IF NOT EXISTS vecs(id INTEGER PRIMARY KEY, v BLOB NOT NULL);
"""


def words(text: str) -> str:
    """'pagerank_by_project' / 'fitGrid' / 'HTMLParser.ts' -> 'pagerank by project' / 'fit grid' / 'html parser ts'."""
    return " ".join(WORD.findall(CAMEL.sub(" ", text or ""))).lower()


def _clean(line: str) -> str:
    if line.lstrip().startswith("#!"):
        return ""
    line = re.sub(r"^\s*(?:///?!?|/\*+|\*+/?|#+|--|;+)\s?", "", line).strip(" *#-=\t")
    return re.sub(r"\s+", " ", line)[:160]


def _prose(text: str, min_words: int = 2) -> str:
    return text if len(re.findall(r"[^\W\d_]{2,}", text)) >= min_words and not NOISE_LINE.match(text) else ""


def summary_of(path: str, head: str) -> str:
    """The first line a file says about itself: a Python module docstring, a Markdown title (a README's first
    paragraph), or the leading comment of a code file. '' when there is none."""
    ext = os.path.splitext(path)[1].lower()
    return _prose(_summary(path, head, ext), 3 if ext == ".txt" else 2)


def _summary(path: str, head: str, ext: str) -> str:
    if ext == ".py":
        m = PY_DOC.match(head)
        if not m:
            return ""
        return next((_clean(x) for x in m.group(2).splitlines() if _clean(x)), "")
    lines = head.splitlines()
    if ext in (".md", ".txt"):
        if lines and lines[0].strip() == "---":  # front matter
            end = next((i for i, x in enumerate(lines[1:], 1) if x.strip() == "---"), 0)
            lines = lines[end + 1:]
        readme = os.path.basename(path).lower().startswith("readme")
        title = ""
        for x in lines:
            s = x.strip()
            if not s or NOISE_LINE.match(s.lstrip("#").strip()) or s.startswith("<"):
                continue
            if s.startswith("#"):
                if not readme:
                    return _clean(s)
                title = title or _clean(s)
                continue
            text = _clean(s)
            return f"{title}: {text}" if readme and title and text else text or title
        return title
    if ext in CODE_COMMENT_EXT:
        for x in lines[:40]:
            s = x.strip()
            if not s:
                continue
            if not s.startswith(("//", "/*", "*", "#", "--")):
                return ""
            text = _clean(s)
            if text and not NOISE_LINE.match(text) and len(text) > 8:
                return text
    return ""


def read_summary(path: str, cache) -> str:
    """summary_of() for a file on disk, remembered by size and mtime."""
    ext = os.path.splitext(path)[1].lower()
    if ext not in CODE_COMMENT_EXT and ext not in (".py", ".md", ".txt"):
        return ""
    stamp = file_stamp(path)
    if stamp is None:
        return ""
    hit = cache.get("summary", path, stamp) if cache else None
    if hit is not None:
        return hit
    if is_excluded(path):
        return ""
    try:
        with open(path, "rb") as fh:
            head = fh.read(HEAD_BYTES).decode("utf-8", errors="replace")
    except OSError:
        return ""
    text = summary_of(path, head)
    if cache:
        cache.put("summary", path, stamp, text)
    return text


def node_texts(store, cache=None) -> list[tuple[int, str, str, str]]:
    """(rowid, name, path words, body) for every node."""
    rows = store.db.execute("SELECT rowid, id, kind, label, path, parent, meta FROM nodes").fetchall()
    children, facts = defaultdict(list), defaultdict(list)
    for r in rows:
        if r["kind"] == "function":
            children[r["parent"]].append(r["label"])
        elif r["kind"] == "fact":
            facts[r["parent"]].append(r["label"])
    label = {r["id"]: r["label"] for r in rows}
    out, summaries = [], []
    for r in rows:
        kind, meta = r["kind"], json.loads(r["meta"])
        name = f"{words(r['label'])} {r['label'].lower()}" if words(r["label"]) != r["label"].lower() else r["label"].lower()
        rel = meta.get("rel") or ""
        path_words = words(os.path.dirname(rel)) if rel else ""
        body = []
        if kind == "file":
            s = read_summary(r["path"], cache) if r["path"] else ""
            if s:
                body.append(s)
                summaries.append((s, r["rowid"]))
            body += children[r["id"]][:30] + facts[r["id"]][:5]
        elif kind == "project":
            s = meta.get("description") or ""
            readme = next((p for p in (os.path.join(r["path"], n) for n in ("README.md", "readme.md", "README.txt"))
                           if os.path.isfile(p)), None) if r["path"] else None
            if readme:
                s = s or read_summary(readme, cache)
            if s:
                body.append(s)
                summaries.append((s, r["rowid"]))
            body += [meta.get("language") or ""] + facts[r["id"]][:5]
        elif kind == "function":
            parent = label.get(r["parent"], "")
            path_words = f"{words(parent)} {path_words}".strip()
        elif kind == "fact":
            body.append(label.get(r["parent"], ""))
        out.append((r["rowid"], name, path_words, " ".join(b for b in body if b)))
    store.db.executemany("UPDATE nodes SET meta=json_set(meta, '$.summary', ?) WHERE rowid=?", summaries)
    return out


def load_model():
    """The static embedding model from the local Hugging Face cache (no network), or None."""
    try:
        os.environ.setdefault("HF_HUB_OFFLINE", "1")
        from model2vec import StaticModel
        return StaticModel.from_pretrained(MODEL)
    except Exception:  # noqa: BLE001 - no package or no cached model: the semantic head stays off
        return None


def embed_text(name: str, path_words: str, body: str) -> str:
    return f"{name}. {path_words}. {body}"[:600]


def build_keys(store, cache=None, embed: bool = True) -> dict:
    store.db.executescript(SCHEMA)
    store.db.execute("DELETE FROM keys")
    store.db.execute("DELETE FROM vecs")
    if cache:
        cache.preload("summary")
    texts = node_texts(store, cache)
    store.db.executemany("INSERT INTO keys(rowid, name, path, body) VALUES(?,?,?,?)", texts)
    model = load_model() if embed else None
    if model is not None:
        import numpy as np
        # one process: worker pools finish sooner on the clock but burn more CPU and linger afterwards
        vecs = model.encode([embed_text(*t[1:]) for t in texts], batch_size=4096, use_multiprocessing=False)
        vecs = vecs.astype(np.float32)
        vecs /= np.linalg.norm(vecs, axis=1, keepdims=True) + 1e-9
        store.db.executemany("INSERT INTO vecs VALUES(?,?)",
                             [(t[0], v.astype(np.float16).tobytes()) for t, v in zip(texts, vecs)])
    with_summary = store.db.execute("SELECT count(*) FROM nodes WHERE json_extract(meta, '$.summary') IS NOT NULL").fetchone()[0]
    return {"ok": len(texts), "summaries": with_summary, "vectors": len(texts) if model is not None else 0}
